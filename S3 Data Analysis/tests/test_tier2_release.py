@pytest.mark.tier2
@pytest.mark.slow
@pytest.mark.parametrize("zone", ["mid", "upper", "lower"])
def test_retrain_paper_csv_with_known_optimal(zone, metric_bands):
    """Fresh retrain on `paper_combined_results.csv` (canonical training
    snapshot) with `use_known_optimal=True`. Acc must land in the
    paper-source band — these are the closest-to-manuscript-publishable
    reproductions we can produce today."""
    paper_csv = S3_ROOT / "paper_combined_results.csv"
    _retrain_test_body(zone, "paper", paper_csv, metric_bands)


@pytest.mark.tier2
@pytest.mark.slow
@pytest.mark.parametrize("zone", ["mid", "upper", "lower"])
def test_retrain_current_csv_with_known_optimal(zone, metric_bands):
    """Fresh retrain on today's pyfaceau combined_results.csv with
    `use_known_optimal=True`. Acc must land in the current-source band."""
    _retrain_test_body(zone, "current_pyfaceau", PYFACEAU_COMBINED_CSV, metric_bands)
